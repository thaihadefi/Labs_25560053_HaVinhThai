// Swagger / OpenAPI 3.0 configuration
const path = require('path');
const swaggerJSDoc = require('swagger-jsdoc');
const swaggerUi = require('swagger-ui-express');

const PORT = process.env.PORT || 3000;

const options = {
  definition: {
    openapi: '3.0.0',
    info: {
      title: 'RESTful API Documentation - Web & Database Lab 3',
      version: '1.0.0',
      description: 'Interactive API documentation auto-generated by Swagger UI for the Sales Management application'
    },
    servers: [
      {
        url: `http://localhost:${PORT}/api`,
        description: 'Development Local Server'
      }
    ],
    components: {
      parameters: {
        idParam: {
          in: 'path',
          name: 'id',
          required: true,
          description: 'MongoDB ObjectId of the resource',
          schema: { type: 'string', example: '6aa7c27316747184e0b762ac' }
        },
        pageParam: {
          in: 'query',
          name: 'page',
          description: 'Current page (default = 1)',
          schema: { type: 'integer', minimum: 1, example: 1 }
        },
        limitParam: {
          in: 'query',
          name: 'limit',
          description: 'Items per page (default = 5)',
          schema: { type: 'integer', minimum: 1, example: 5 }
        }
      },
      schemas: {
        ProductPagination: {
          type: 'object',
          properties: {
            currentPage: { type: 'integer', example: 1 },
            totalPages: { type: 'integer', example: 3 },
            totalProducts: { type: 'integer', example: 12 }
          }
        },
        CategoryPagination: {
          type: 'object',
          properties: {
            currentPage: { type: 'integer', example: 1 },
            totalPages: { type: 'integer', example: 1 },
            totalCategories: { type: 'integer', example: 3 }
          }
        },
        Error: {
          type: 'object',
          properties: {
            success: { type: 'boolean', example: false },
            error: { type: 'string', example: 'Error message' }
          }
        },
        Message: {
          type: 'object',
          properties: {
            success: { type: 'boolean', example: true },
            message: { type: 'string', example: 'Deleted successfully' }
          }
        }
      },
      responses: {
        BadRequest: {
          description: 'Invalid input or malformed ID',
          content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } }
        },
        NotFound: {
          description: 'No resource found with the given ID',
          content: {
            'application/json': {
              schema: {
                type: 'object',
                properties: {
                  success: { type: 'boolean', example: false },
                  message: { type: 'string', example: 'No resource found with the given ID' }
                }
              }
            }
          }
        },
        Conflict: {
          description: 'Duplicate value on a unique field',
          content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } }
        }
      }
    }
  },
  apis: [path.join(__dirname, '../routes/*.js')]
};

const swaggerSpec = swaggerJSDoc(options);

const setupSwagger = (app) => {
  app.use('/api-docs', swaggerUi.serve, swaggerUi.setup(swaggerSpec));
  console.log(`Swagger UI documentation is ready at: http://localhost:${PORT}/api-docs`);
};

module.exports = setupSwagger;
